def _load_full_playlist_catalog() -> list[dict[str, Any]]:
    import json
    from pathlib import Path

    catalog_path = Path(__file__).parent / "broadcast_playlist_catalog.json"
    if catalog_path.exists():
        with open(catalog_path, "r", encoding="utf-8") as f:
            return json.load(f)
    return []


_PLAYLIST_CATALOG_BY_VID: dict[str, dict[str, Any]] = {
    f"yt-pl-{item['yt_id']}": item for item in _load_full_playlist_catalog()
}


def get_playlist_teams_for_video(video_id: str, title: str = "") -> tuple[str, str]:
    """Return (home_team, away_team) for any playlist video ID."""
    meta = _PLAYLIST_CATALOG_BY_VID.get(video_id)
    if meta:
        return str(meta.get("home_team", "HOME")), str(meta.get("away_team", "AWAY"))
    return "HOME", "AWAY"


