def _fmt_mmss(total_sec: int) -> str:
    mins = total_sec // 60
    secs = total_sec % 60
    return f"{mins:02d}:{secs:02d}"


def _compute_game_clock(ts_sec: int, duration_seconds: int, single_half_period: str | None = None) -> tuple[str, str]:
    """Map broadcast video timestamp to NCAA period ('1ST' or '2ND') and game clock ('MM:SS')."""
    if single_half_period:
        frac = min(max(ts_sec / max(duration_seconds, 1), 0.0), 1.0)
        rem_sec = int(round((1.0 - frac) * 1200))
        return single_half_period, _fmt_mmss(rem_sec)

    half_point = duration_seconds // 2
    if ts_sec < half_point:
        frac = min(max(ts_sec / max(half_point, 1), 0.0), 1.0)
        rem_sec = int(round((1.0 - frac) * 1200))
        return "1ST", _fmt_mmss(rem_sec)
    else:
        frac = min(max((ts_sec - half_point) / max(duration_seconds - half_point, 1), 0.0), 1.0)
        rem_sec = int(round((1.0 - frac) * 1200))
        return "2ND", _fmt_mmss(rem_sec)


